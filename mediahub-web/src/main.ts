/**
 * main.ts - Vue 3 应用入口文件
 *
 * 功能说明:
 * 这是整个前端应用的入口点，负责初始化 Vue 应用并挂载到 DOM 上。
 * 类似于传统 Web 应用中的 main() 函数，是程序执行的起点。
 */

// ============================================================
// 1. 导入 Vue 3 的 createApp 函数
// ============================================================
// createApp 是 Vue 3 的核心函数，用于创建一个新的应用实例
// 相比 Vue 2 的 new Vue()，createApp 更加模块化和解耦
import { createApp } from 'vue'

// ============================================================
// 2. 导入全局样式文件
// ============================================================
// 引入全局 CSS 样式，定义页面基础样式、主题色、按钮样式等
// 使用相对路径引用当前目录下的 style.css
import './style.css'

// ============================================================
// 3. 导入根组件
// ============================================================
// 引入 App.vue 根组件，这是整个应用的顶层组件
// 所有其他组件都会被包含在 App.vue 内部
// .vue 文件会被 Vite + Vue 插件自动解析
import App from './App.vue'

// ============================================================
// 4. 导入 Element Plus UI 组件库
// ============================================================
// Element Plus 是一个基于 Vue 3 的组件库，提供了丰富的 UI 组件
// 如按钮、表单、对话框、卡片、轮播图等，加速前端开发
import ElementPlus from 'element-plus'

// ============================================================
// 5. 导入 Element Plus 的全局 CSS 样式
// ============================================================
// Element Plus 自带的样式文件，必须引入才能让组件正常显示
// 包含了所有组件的基础样式和主题
import 'element-plus/dist/index.css'

// ============================================================
// 6. 创建并启动 Vue 应用
// ============================================================
// createApp(App) - 创建 Vue 应用实例，传入根组件 App
// .use(ElementPlus) - 注册 Element Plus 插件，使所有组件可用
// .mount('#app') - 将应用挂载到 DOM 元素上
// '#app' 是 index.html 中 <div id="app"></div> 的选择器
// 应用启动后，Vue 会将 App.vue 的内容渲染到这个 div 中
createApp(App).use(ElementPlus).mount('#app')
